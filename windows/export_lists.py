#!/usr/bin/env python3
"""Export BuiltinLists.kt and BlocklistUpdater.SOURCES into windows/kit/lists.txt.

The Windows kit is a blocker-only clone of the phone: it must apply exactly the same
domain rules, so the rules are generated from the Kotlin source instead of being copied.
Run after every change to BuiltinLists.kt (the unit test in the kit checks it is current).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LISTS_KT = ROOT / "app/src/main/java/com/focusguard/net/BuiltinLists.kt"
UPDATER_KT = ROOT / "app/src/main/java/com/focusguard/net/BlocklistUpdater.kt"
EXTRA = Path(__file__).resolve().parent / "extra_lists.txt"
OUT = Path(__file__).resolve().parent / "kit/lists.txt"

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def strip_comments(src: str) -> str:
    """Remove // and /* */ comments without touching string literals ("https://...")."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1])
            i = j + 1
        elif src.startswith("//", i):
            i = src.find("\n", i)
            i = n if i < 0 else i
        elif src.startswith("/*", i):
            i = src.find("*/", i) + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def body(src: str, name: str) -> str:
    """Text between the opening and matching closing paren/brace of `val name = xxx(`."""
    m = re.search(r"val\s+" + name + r"\b[^=]*=\s*\w+\s*([({])", src)
    if not m:
        sys.exit(f"{name} not found in {LISTS_KT}")
    open_ch = m.group(1)
    close_ch = ")" if open_ch == "(" else "}"
    i = m.end()
    depth = 1
    start = i
    while depth:
        c = src[i]
        if c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
        i += 1
    return src[start:i - 1]


def strings(text: str) -> list[str]:
    return [s.encode().decode("unicode_escape") for s in STRING.findall(text)]


def main() -> None:
    src = strip_comments(LISTS_KT.read_text())
    sections: dict[str, list[str]] = {}
    for name in ("allow", "block", "strongKeywords", "strongKeywordExceptions", "tokenKeywords"):
        sections[name] = strings(body(src, name))

    # safeSearchRewrite is a buildMap with a loop over google ccTLDs plus explicit put()s
    rw = body(src, "safeSearchRewrite")
    loop = re.search(r"for\s*\(\s*h\s+in\s+listOf\((.*?)\)\s*\)\s*\{(.*?)\n\s*\}", rw, flags=re.S)
    if not loop:
        sys.exit("safeSearchRewrite loop not understood")
    hosts = strings(loop.group(1))
    puts = re.findall(r'put\(\s*(h|"[^"]*")\s*,\s*"([^"]*)"\s*\)', loop.group(2))
    if not puts:
        sys.exit("safeSearchRewrite loop body not understood")
    rewrite: list[str] = []
    for h in hosts:
        for key, target in puts:
            key = h if key == "h" else key.strip('"').replace("$h", h)
            rewrite.append(f"{key} {target}")
    rest = rw[loop.end():]
    for key, target in re.findall(r'put\(\s*"([^"]*)"\s*,\s*"([^"]*)"\s*\)', rest):
        rewrite.append(f"{key} {target}")
    sections["safeSearchRewrite"] = rewrite

    upd = strip_comments(UPDATER_KT.read_text())
    hagezi = re.search(r'HAGEZI\s*=\s*"([^"]*)"', upd).group(1)
    srcs = body(upd, "SOURCES")
    sources = []
    for s in re.findall(r'"((?:[^"\\]|\\.)*)"', srcs):
        sources.append(s.replace("$HAGEZI", hagezi))
    sections["sources"] = sources

    # Windows-only additions (laptop is browsing-heavier than the phone): one "section item" per line
    if EXTRA.exists():
        section = None
        for line in EXTRA.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if line.startswith("[") and line.endswith("]"):
                section = line[1:-1]
                continue
            if section not in sections:
                sys.exit(f"extra_lists.txt: unknown section {section!r}")
            if line not in sections[section]:
                sections[section].append(line)

    out = ["# generated by windows/export_lists.py from BuiltinLists.kt + extra_lists.txt — do not edit"]
    for name, items in sections.items():
        out.append(f"[{name}]")
        out.extend(items)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    for name, items in sections.items():
        print(f"{name}: {len(items)}")


if __name__ == "__main__":
    main()
